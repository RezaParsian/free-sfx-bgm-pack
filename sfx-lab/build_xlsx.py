"""build_xlsx.py — ساخت جدول اکسل کامل کتابخانه‌ی صوتی"""
import os
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

OUT = os.environ.get("OUTDIR", "guides/audio-library.xlsx")

HEAD = PatternFill("solid", fgColor="1F2937")
BAND = PatternFill("solid", fgColor="F3F4F6")
SEC = PatternFill("solid", fgColor="DBEAFE")
WHITE = Font(color="FFFFFF", bold=True, size=11)
BOLD = Font(bold=True)
THIN = Side(style="thin", color="D1D5DB")
BOX = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
WRAP = Alignment(wrap_text=True, vertical="top", horizontal="right", readingOrder=2)
CTR = Alignment(horizontal="center", vertical="center", readingOrder=2)


def sheet(wb, title, headers, rows, widths, name_col=None):
    ws = wb.create_sheet(title)
    ws.sheet_view.rightToLeft = True
    for c, h in enumerate(headers, 1):
        cell = ws.cell(1, c, h)
        cell.fill, cell.font, cell.border, cell.alignment = HEAD, WHITE, BOX, CTR
    for r, row in enumerate(rows, 2):
        for c, v in enumerate(row, 1):
            cell = ws.cell(r, c, v)
            cell.border = BOX
            cell.alignment = WRAP if (name_col is None or c != name_col) else Alignment(
                horizontal="left", vertical="top")
            if r % 2 == 0:
                cell.fill = BAND
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(headers))}{len(rows)+1}"
    ws.row_dimensions[1].height = 26
    return ws


wb = Workbook()
wb.remove(wb.active)

